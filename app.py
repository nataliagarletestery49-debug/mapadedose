colunas = ['X', 'Y', 'Z', 'Dose', 'Incerteza', 'IX', 'IY', 'IZ']

def baixar_do_drive(id_drive, caminho_destino):
    if not os.path.exists(caminho_destino) or os.path.getsize(caminho_destino) < 1000000:
        url = f"https://drive.usercontent.google.com/download?id={id_drive}&export=download&confirm=t"
        resposta = requests.get(url, stream=True)
        with open(caminho_destino, "wb") as f:
            for bloco in resposta.iter_content(chunk_size=32768):
                if bloco:
                    f.write(bloco)

def carregar_dose_penmain(caminho):
    """
    Lê o ficheiro .dat do PENMAIN e devolve a matriz 3D com precisão float32
    para poupar memória RAM.
    """
    df = pd.read_csv(
        caminho,
        sep=r'\s+',
        comment='#',
        names=colunas,
        on_bad_lines='skip'
    ).dropna()

    df['IX'] = df['IX'].astype(int) - 1
    df['IY'] = df['IY'].astype(int) - 1
    df['IZ'] = df['IZ'].astype(int) - 1

    nbx = int(df['IX'].max()) + 1
    nby = int(df['IY'].max()) + 1
    nbz = int(df['IZ'].max()) + 1

    dose_3d = np.zeros((nbx, nby, nbz), dtype=np.float32)
    dose_3d[df['IX'].values, df['IY'].values, df['IZ'].values] = df['Dose'].values

    x_coords = np.sort(df['X'].unique())
    y_coords = np.sort(df['Y'].unique())
    z_coords = np.sort(df['Z'].unique())

    return dose_3d, x_coords, y_coords, z_coords

@st.cache_data(show_spinner="A carregar simulações... Por favor, aguarde.")
def processar_simulacoes():
    baixar_do_drive(id_frente, caminho_frente)
    baixar_do_drive(id_tras, caminho_tras)

    # 1. Carregar ambas as simulações
    dose_frente, x_coords, y_coords, z_coords = carregar_dose_penmain(caminho_frente)
    dose_tras, _, _, _ = carregar_dose_penmain(caminho_tras)

    # 2. Sobreposição física (Adição linear direta dos campos opostos)
    dose_combinada = dose_frente + dose_tras

    # 3. Normalização pelo percentil 99.5% para evitar saturação por ruído estatístico
    doses_validas = dose_combinada[dose_combinada > 1e-10]
    ref_maxima = np.percentile(doses_validas, 99.5) if len(doses_validas) > 0 else dose_combinada.max()
    dose_normalizada = (dose_combinada / ref_maxima) * 100.0

    limites_xy = [float(x_coords.min()), float(x_coords.max()), float(y_coords.min()), float(y_coords.max())]
    nbz = int(dose_combinada.shape[2])

    return dose_normalizada, limites_xy, z_coords, nbz

dose_normalizada, limites_xy, z_coords, nbz = processar_simulacoes()

